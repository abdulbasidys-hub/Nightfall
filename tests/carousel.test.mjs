import test from 'node:test';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);

test('featured carousel rotates, pauses, supports navigation and swipe, and respects reduced motion',()=>{
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
require('tsx/cjs');
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost'});
global.window=dom.window;
global.document=dom.window.document;
global.HTMLElement=dom.window.HTMLElement;
global.IS_REACT_ACT_ENVIRONMENT=true;
let clock=0,sequence=0;
const frames=new Map(),motionListeners=new Set();
Object.defineProperty(performance,'now',{value:()=>clock,configurable:true});
global.requestAnimationFrame=fn=>{frames.set(++sequence,fn);return sequence;};
global.cancelAnimationFrame=id=>frames.delete(id);
let reduced=false;
window.matchMedia=()=>({get matches(){return reduced;},addEventListener:(_,fn)=>motionListeners.add(fn),removeEventListener:(_,fn)=>motionListeners.delete(fn)});
Object.defineProperty(document,'hidden',{value:false,configurable:true,writable:true});
const React=require('react');
const {act}=React;
const {createRoot}=require('react-dom/client');
const {FeaturedCarousel}=require('../src/components/FeaturedCarousel.tsx');
const root=createRoot(document.querySelector('#root'));
const items=['One','Two','Three'].map(title=>({id:title,title,node:React.createElement('a',{href:'/'+title},title)}));
const current=()=>document.querySelector('.featured-slide.is-active')?.getAttribute('aria-label');
const frame=ms=>{clock+=ms;const pending=[...frames.values()];frames.clear();act(()=>pending.forEach(fn=>fn(clock)));};
const click=label=>act(()=>document.querySelector(`[aria-label="${label}"]`).click());
act(()=>root.render(React.createElement(FeaturedCarousel,{items})));
assert.match(current(),/^1 of 3/);
assert.equal(document.querySelectorAll('.featured-slide[inert]').length,2);
frame(5999);assert.match(current(),/^1 of 3/);
frame(1);assert.match(current(),/^2 of 3/);
frame(6000);assert.match(current(),/^3 of 3/);
frame(6000);assert.match(current(),/^1 of 3/);
frame(2000);
click('Pause slideshow');frame(12000);assert.match(current(),/^1 of 3/);
click('Play slideshow');frame(3999);assert.match(current(),/^1 of 3/);
frame(1);assert.match(current(),/^2 of 3/);
click('Previous featured project');assert.match(current(),/^1 of 3/);
click('Show Three');assert.match(current(),/^3 of 3/);
const carousel=document.querySelector('.featured-carousel');
act(()=>carousel.dispatchEvent(new window.KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true})));
assert.match(current(),/^1 of 3/);
const link=document.querySelector('.is-active a');
act(()=>link.focus());frame(12000);assert.match(current(),/^1 of 3/);
act(()=>link.blur());frame(6000);assert.match(current(),/^2 of 3/);
act(()=>{reduced=true;motionListeners.forEach(fn=>fn());});
frame(12000);assert.match(current(),/^2 of 3/);
click('Next featured project');assert.match(current(),/^3 of 3/);
act(()=>{reduced=false;motionListeners.forEach(fn=>fn());});
act(()=>{document.hidden=true;document.dispatchEvent(new window.Event('visibilitychange'));});
frame(12000);assert.match(current(),/^3 of 3/);
act(()=>{document.hidden=false;document.dispatchEvent(new window.Event('visibilitychange'));});
frame(6000);assert.match(current(),/^1 of 3/);
function touchEvent(type,x,y){const event=new window.Event(type,{bubbles:true});Object.defineProperty(event,type==='touchstart'?'touches':'changedTouches',{value:[{clientX:x,clientY:y}]});return event;}
act(()=>carousel.dispatchEvent(touchEvent('touchstart',250,100)));
act(()=>carousel.dispatchEvent(touchEvent('touchend',100,105)));
assert.match(current(),/^2 of 3/);
act(()=>root.render(React.createElement(FeaturedCarousel,{key:'single',items:items.slice(0,1)})));
assert.equal(document.querySelector('.featured-controls'),null);
frame(12000);assert.match(current(),/^1 of 1/);
act(()=>root.unmount());
dom.window.close();

});
